// Generates old-wxt.js / new-wxt.js — the byte slices cited in README.md — from the
// bundles reproduce.sh builds. Nothing here is hand-transcribed: every offset and hash
// in the output is computed from the file and the slices are verbatim `slice()` results,
// so a reader can re-run this and diff the result against what is committed.
//
//   node make-slices.mjs <temp-root> [output-dir]

import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const T = process.argv[2]
if (!T) throw new Error('usage: node make-slices.mjs <temp-root> [output-dir]')
const OUT = process.argv[3] ?? path.dirname(fileURLToPath(import.meta.url))

// freeGlobal's assignment through the `Function('return this')()` fallback: the three
// lines of lodash/_root.js this all comes down to, as emitted.
const CHAIN = /[\w$]+=typeof \w+==[`"']object[`"']&&\w+&&\w+\.Object===Object&&\w+/
const CALL = /Function\([^)]*\)\(\)/
const SHIM = /var \w+=typeof globalThis<"u"\?globalThis(?::typeof \w+<"u"\?\w+)*:\{\}/

const SETS = [
  {
    k: 'old-wxt',
    desc: 'wxt 0.20.7 — vite 6.4.3 + rollup 4.63.4 (the toolchain v1.0.1 shipped with)',
    dir: 'old',
    expect: 'shim present — freeGlobal is truthy, so the `||` short-circuits and this build survives',
  },
  {
    k: 'new-wxt',
    desc: 'wxt 0.20.27 — vite 8.3.0 + rolldown 1.2.9 (the toolchain v1.1.0 shipped with)',
    dir: 'new',
    expect: 'no shim — freeGlobal is falsy, the third operand runs, and Firefox blocks it',
  },
]

for (const x of SETS) {
  const file = `${T}/${x.dir}/.output/firefox-mv3/content-scripts/content.js`
  const s = fs.readFileSync(file, 'utf8')
  const sha = crypto.createHash('sha256').update(Buffer.from(s)).digest('hex')
  const size = Buffer.byteLength(s)

  const chainAt = s.search(CHAIN)
  const call = s.slice(chainAt).match(CALL)
  const chain = s.slice(chainAt, chainAt + call.index + call[0].length)
  const shim = s.match(SHIM)
  const shimAt = shim ? s.indexOf(shim[0]) : -1
  const fh = s.indexOf('Function(')
  const bound = chain.match(/typeof (\w+)==/)[1]

  const L = []
  L.push('// EXACT BYTE SLICE — generated by make-slices.mjs, do not hand-edit.')
  L.push('//')
  L.push(`// artifact : ${x.k} — ${x.desc}`)
  L.push('// origin   : repro/ built with that wxt version; everything else identical')
  L.push(`// bytes    : ${size}`)
  L.push(`// sha256   : ${sha}`)
  L.push(`// expected : ${x.expect}`)
  L.push('')
  L.push('')
  L.push(`### first \`Function(\` in the bundle, at byte ${fh}`)
  L.push('// Present in both builds. In old-wxt it is unreachable; in new-wxt it runs.')
  L.push(s.slice(fh - 60, fh + 40))
  L.push('')
  L.push('')
  if (shim) {
    L.push(`### the injected \`global\` shim, at byte ${shimAt}`)
    L.push('// The only reason freeGlobal is not a bare `global`. rollup emits this;')
    L.push('// rolldown does not — that is the whole regression.')
    L.push(shim[0])
    L.push('')
    L.push('')
    L.push(`### lodash _root.js — the chain that decides everything, at byte ${chainAt}`)
    L.push(`// freeGlobal is bound to the shim variable \`${bound}\`, which is the sandbox's own`)
    L.push(`// globalThis, so \`${bound}.Object === Object\` is TRUE and the Function operand`)
    L.push('// is never evaluated.')
  }
  else {
    L.push(`### lodash _root.js — the chain that decides everything, at byte ${chainAt}`)
    if (bound !== 'global') throw new Error(`expected a bare global, got ${bound}`)
    L.push('// freeGlobal is bound to a BARE `global` — no shim exists anywhere in this bundle,')
    L.push('// so inside the Firefox content-script sandbox `global` is undefined, `self` is the')
    L.push('// Xray-wrapped page window (self.Object !== Object), and the third operand — the')
    L.push('// one the CSP blocks — finally runs.')
  }
  L.push(chain)

  fs.writeFileSync(path.join(OUT, `${x.k}.js`), `${L.join('\n')}\n`)
  console.log(`${x.k}: ${size} B, sha ${sha.slice(0, 16)}…, Function( @${fh}, shim=${shim ? 'PRESENT' : 'absent'}, bound=${bound}`)
}
